async function phone(S, h) {
  const o = await h.choose([{ t: '911' }, { t: 'Джесс' }, { t: 'Набрать номер вручную' }, { t: 'Не звонить' }]);
  if (o.t === 'Не звонить') return;
  let num = o.t === '911' ? '911' : o.t === 'Джесс' ? 'jess' : await h.m.dialer({});
  S.bat = Math.max(0, S.bat - 2);
  if (num === '911') return S.f.called911 ? call911again(S, h) : call911(S, h);
  if (num === 'jess') { await h.para('Вызов сорвался на втором гудке. Я попробовал ещё раз, и ещё, но телефон каждый раз показывал одно и то же: «Вызов не выполнен». Одной полоски хватало только на что-то одно, и это одно было не Джесс.'); return }
  await h.para('В трубке долго стояла тишина, а потом механический голос сообщил, что набранный номер недоступен.');
}

async function call911(S, h) {
  S.f.called911 = 1;
  await h.para('Гудки шли так долго, что я успел их пересчитать: пять, шесть. На шестом в трубке щёлкнуло, и спокойный женский голос с лёгкой хрипотцой произнёс те самые слова, которые я слышал по радио час назад:');
  h.call('Дениз · 911', '911', 'evil');
  await h.say('d', 'Девять-один-один, что у вас случилось?');
  await h.timed([{ t: '«Я разбил{g:ся|ась}. Forest Road 2254»', say: 'Я разбил{g:ся|ась}. Машина в кювете, Forest Road 2254, где-то в шести милях от шоссе.' }, { t: '«Помогите, я ранен{g:|а}»', say: 'Помогите, я ранен{g:|а}. Машина в кювете.' }], 9);
  await h.say('d', 'Хорошо, милый. Я вас слышу. Главное сейчас — не выходить из машины, что бы вы ни увидели и что бы ни услышали. Мотор заводите на десять минут в час, не дольше, и сначала проверьте, не завалило ли снегом выхлопную трубу.');
  await h.para('Все её советы были правильными, я читал их когда-то в статье про зимние дороги, и от этой правильности мне стало спокойнее. Только гораздо позже я понял, что она так и не спросила, как меня зовут и по какому номеру мне перезвонить.');
  await h.say('d', 'Скажите, вы там один?');
  const a = await h.timed([{ t: '«Да. Один»', say: 'Да. Один{g:|а}.', fx: 1 }, { t: '«А почему вы спрашиваете?»', say: 'А почему вы спрашиваете?' }], 7);
  if (a.fx) { S.f.saidAlone = 1; await h.say('d', 'Это хорошо.'); await h.para('Она сказала это так тепло, что я не сразу заметил, насколько странно это прозвучало.') }
  else if (a.silence) await h.say('d', 'Вы меня слышите, милый? Мне просто нужно знать, сколько вас там.');
  else await h.say('d', 'Мне просто нужно знать, сколько вас там, милый.');
  const f = await h.choose([{ t: '«На дороге кто-то стоял»', say: 'На дороге кто-то стоял. Из-за него я и съехал{g:|а}.' }, { t: 'Не говорить о фигуре' }]);
  if (f.say) { await h.say('d', 'А он вас разглядел?'); await h.para('Я открыл рот, чтобы ответить, и понял, что не знаю, что на это можно ответить.') }
  await h.say('d', 'Сидите в машине и ждите. Помощь уже едет.');
  h.endcall();
  await h.para('Связь оборвалась сама, без гудков. Я посмотрел на экран и долго не мог понять, что вижу: вызов длился три секунды.');
}
